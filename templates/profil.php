    <h2>Fra cykler til Jaguar</h2>
    <p>Firmaet H. Rasmussen blev grundlagt i Brovst den 1. april 1907 af Svend Hulthin Rasmussen, den nuværende ejers bedstefar. Gennem årene har virksomheden dækket mange brancher: cykler, knallerter, maskinværksted, elværk, teglværk og naturligvis biler.</p>
    <p>Firmaet tegnes i dag af Hans Hulthin Rasmussen, der er vokset op i firmaet og har fået kærligheden til især de engelske biler i blodet fra barnsben. Han blev ansat i 1971, fik ansvaret for reservedelslageret i 1976 og overtog den 1. januar 1986 virksomheden efter sin far, Vagn Hulthin Rasmussen.</p>
