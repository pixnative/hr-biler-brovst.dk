    <h2>Jaguar, Land Rover samt MG, Rover</h2>
    <p>H. Rasmussen Biler har tidligere været autoriseret Skoda-forhandler i 22 år og autoriseret Rover- og Land Rover-forhandler i ca. 12 år. Begge aftaler blev opsagt på grund af ændringer i den landsdækkende forhandlerstruktur, men vi blev efterfølgende autoriseret værksted for Rover og Land Rover – og som noget nyt også Jaguar.</p>
    <p>Pr. 1. januar 2017 opsagde vi vores medvirken i det autoriserede forhandler- og værkstedsnet. Fra den dato er vi Special Værksted for Jaguar, Land Rover og Rover, stadig med dag-til-dag-levering af originale reservedele fra JLR-importøren i Kolding.</p>
